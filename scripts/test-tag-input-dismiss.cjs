const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM} = require('jsdom');
const coffee = require('coffeescript');
const dom = new JSDOM('<body><button id="outside">Outside</button></body>', {runScripts:'outside-only'});
const w=dom.window; w.$=require('jquery')(w); w._=require('lodash');
w.eval(fs.readFileSync('node_modules/angular/angular.js','utf8'));
const app=w.angular.module('taigaCommon',[]);
app.controller('TagLineCommonCtrl',function(){this.addTag=false;this.newTag={name:'',color:null};this.displayTagInput=()=>this.addTag=true;this._createColorsArray=()=>[];});
w.eval(coffee.compile(fs.readFileSync('app/modules/components/tags/tag-line-common/tag-line-common.directive.coffee','utf8')));
const injector=w.angular.injector(['ng','taigaCommon']),root=injector.get('$rootScope');
injector.get('$templateCache').put('components/tags/tag-line-common/tag-line-common.html','<button ng-if="!vm.addTag" ng-click="vm.displayTagInput()">Add tag</button><div ng-if="vm.addTag"><input class="tag-input"><button class="color">Color</button></div>');
const scope=root.$new(),el=injector.get('$compile')('<div tg-tag-line-common></div>')(scope);w.$('body').append(el);root.$digest();
el.find('button').trigger('click');root.$digest();assert.equal(el.find('input').length,1);
el.find('.color').trigger('click');root.$digest();assert.equal(el.find('input').length,1,'color selection stays open');
w.$('#outside').trigger('mousedown');root.$digest();assert.equal(el.find('input').length,0);assert.match(el.text(),/Add tag/);
el.find('button').trigger('click');root.$digest();assert.equal(el.find('input').length,1);
scope.$destroy();el.remove();w.$('#outside').trigger('mousedown');root.$digest();dom.window.close();
console.log('PASS: outside clicks dismiss tag input, inside controls stay open, reopening and scope cleanup');
