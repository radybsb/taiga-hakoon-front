const fs = require('fs');
const path = require('path');
const assert = require('assert');
process.chdir(path.resolve(__dirname, '..'));
const {JSDOM} = require('jsdom');
const coffee = require('coffeescript');
const jade = require('jade');
const dom = new JSDOM('<body></body>', {runScripts: 'outside-only', url: 'http://localhost/'});
const w = dom.window;
w.$ = require('jquery')(w);
w._ = require('lodash');
w.eval(fs.readFileSync('node_modules/angular/angular.js','utf8'));
const app = w.angular.module('taigaComponents', []);
const Immutable = require('immutable');
app.value('$tgLocation', {url: () => {}});
let popupOpens=0;app.value('tgDetailPopup', {open:(route,target)=>{assert.equal(route,'project-userstories-detail');assert.equal(target.project,'demo');assert.equal(target.ref,12);popupOpens++;}});
app.factory('$exceptionHandler', () => error => {throw error;});
app.value('$tgNavUrls', {resolve: (key, args) => {assert.equal(key, 'project-userstories-detail'); return `project/${args.project}/us/${args.ref}`;}});
app.filter('emojify', ['$sce', sce => text => sce.trustAsHtml(text)]);
w.eval(coffee.compile(fs.readFileSync('app/modules/components/card/card.controller.coffee','utf8')));
const injector = w.angular.injector(['ng','taigaComponents']);
const scope = injector.get('$rootScope').$new();
const vm = scope.vm = injector.get('$controller')('Card', {$scope: scope});
vm.project = {slug: 'demo', my_permissions: ['view_us']};
vm.item = Immutable.fromJS({id: 8, model: {ref: 12, subject: 'Task'}});
vm.getLinkParams = () => ({});
vm.type = 'us'; vm.zoom = ['ref','subject']; vm.zoomLevel = 1;

const el = injector.get('$compile')(jade.renderFile('app/modules/components/card/card-templates/card-title.jade'))(scope);
w.$('body').append(el); scope.$digest();
const link = el.find('a')[0];
assert.equal(link.getAttribute('href'),'project/demo/us/12');
function click(options = {}) {const event = new w.MouseEvent('click',{bubbles: true, cancelable: true, ...options}); link.dispatchEvent(event); return event;}
assert(click().defaultPrevented); assert.equal(popupOpens,1);
for (const options of [{ctrlKey:true},{metaKey:true},{shiftKey:true},{altKey:true},{button:1},{button:2}]) assert.equal(click(options).defaultPrevented,false);
assert.equal(popupOpens,1);
vm.item = vm.item.set('loading-edit',true); scope.$digest(); click(); assert.equal(popupOpens,1);
vm.item=vm.item.set('loading-edit',false);scope.$digest();
vm.openCard(new w.MouseEvent('click',{button:0,cancelable:true}));assert.equal(popupOpens,2,'Card body must open the same story popup');
scope.$destroy(); dom.window.close();
console.log('PASS: Kanban story title/body open full popup with view permission; real story href and modified/middle clicks preserve browser navigation; duplicate clicks blocked');
