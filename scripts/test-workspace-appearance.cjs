const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM} = require('jsdom');
const coffee = require('coffeescript');
const jade = require('jade');
const path = require('node:path');
process.chdir(path.resolve(__dirname, '..'));
const source = fs.readFileSync('app/modules/components/kanban-appearance/kanban-appearance.coffee', 'utf8');
function setup(saved, blocked = false, legacy = false) {
    const dom = new JSDOM('<html><body></body></html>', {url:'http://localhost', runScripts:'outside-only'});
    const w = dom.window;
    if (saved) w.localStorage.setItem('taiga.workspace.appearance', saved);
    if (blocked) Object.defineProperty(w, 'localStorage', {get() {throw Error('blocked');}});
    let listener;
    const media = {matches: false};
    media[legacy ? 'addListener' : 'addEventListener'] = (...args) => {listener = args.at(-1);};
    w.matchMedia = () => media;
    w.eval(fs.readFileSync('node_modules/angular/angular.js', 'utf8'));
    w.angular.module('taigaComponents', []).filter('translate', () => value => value);
    w.eval(coffee.compile(source));
    const injector = w.angular.injector(['ng', 'taigaComponents']);
    const service = injector.get('tgWorkspaceAppearance');
    return {dom,w,media,service,injector,change() {listener();}};
}
const ctx = setup();
const root = ctx.w.document.documentElement;
assert.equal(ctx.service.preference, 'system');
assert.equal(root.getAttribute('data-workspace-appearance'), 'light');
ctx.media.matches = true; ctx.change();
assert.equal(root.getAttribute('data-workspace-appearance'), 'dark');
ctx.service.set('light'); ctx.change();
assert.equal(root.getAttribute('data-workspace-appearance'), 'light');
assert.equal(ctx.w.localStorage.getItem('taiga.workspace.appearance'), 'light');
ctx.service.set('invalid'); assert.equal(ctx.service.preference, 'light');
const scope = ctx.injector.get('$rootScope').$new();
const el = ctx.injector.get('$compile')('<div tg-modern-workspace></div>')(scope);
ctx.w.document.body.append(el[0]); scope.$digest();
assert.equal(root.getAttribute('data-modern-workspace'), 'kanban');
ctx.injector.get('$templateCache').put('components/kanban-appearance/kanban-appearance.html', jade.renderFile('app/modules/components/kanban-appearance/kanban-appearance.jade'));
const picker = ctx.injector.get('$compile')('<tg-workspace-theme-toggle></tg-workspace-theme-toggle>')(scope);
ctx.w.document.body.append(picker[0]); scope.$digest();
const button = picker[0].querySelector('button');
assert.equal(button.getAttribute('aria-label'), 'COMMON.APPEARANCE.APPLY_DARK');
const originalIcon = picker[0].querySelector('svg');
const originalPath = originalIcon.querySelector('path');
const moonPath = originalPath.getAttribute('d');
button.click(); scope.$digest();
assert.equal(picker[0].querySelector('svg'), originalIcon);
assert.equal(originalIcon.querySelector('path'), originalPath);
assert.notEqual(originalPath.getAttribute('d'), moonPath);
assert.equal(button.getAttribute('aria-label'), 'COMMON.APPEARANCE.APPLY_LIGHT');
assert.equal(picker[0].querySelectorAll('svg').length, 1);
button.click(); scope.$digest();
assert.equal(root.getAttribute('data-workspace-appearance'), 'light');
button.click(); scope.$digest();
assert.equal(root.getAttribute('data-workspace-appearance'), 'dark');
assert.equal(ctx.w.localStorage.getItem('taiga.workspace.appearance'), 'dark');
scope.$destroy(); assert.equal(root.hasAttribute('data-modern-workspace'), false);
const backlogScope = ctx.injector.get('$rootScope').$new();
ctx.injector.get('$compile')('<div tg-modern-workspace="backlog"></div>')(backlogScope);
backlogScope.$digest();
assert.equal(root.getAttribute('data-modern-workspace'), 'backlog');
assert.equal(root.getAttribute('data-workspace-appearance'), 'dark');
backlogScope.$destroy();
assert.equal(root.hasAttribute('data-modern-workspace'), false);
const taskboardScope = ctx.injector.get('$rootScope').$new();
ctx.injector.get('$compile')('<div tg-modern-workspace="taskboard"></div>')(taskboardScope);
taskboardScope.$digest();
assert.equal(root.getAttribute('data-modern-workspace'), 'taskboard');
taskboardScope.$destroy();
assert.equal(root.hasAttribute('data-modern-workspace'), false);
ctx.dom.window.close();
for (const [saved,blocked,legacy] of [['dark',false,false],['invalid',false,true],[null,true,false]]) {
    const c=setup(saved,blocked,legacy);
    assert.equal(c.service.preference, saved==='dark'?'dark':'system');
    c.service.set('system'); c.media.matches=true; c.change();
    assert.equal(c.w.document.documentElement.getAttribute('data-workspace-appearance'),'dark');
    c.dom.window.close();
}
console.log('PASS: appearance persistence, native picker, system changes, scope cleanup, invalid preferences and unavailable storage');
