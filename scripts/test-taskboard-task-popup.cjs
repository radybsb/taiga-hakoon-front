w.eval(coffee.compile(fs.readFileSync('app/modules/components/card/card.controller.coffee','utf8')));
const injector = w.angular.injector(['ng','taigaComponents']);
const scope = injector.get('$rootScope').$new();
const vm = scope.vm = injector.get('$controller')('Card', {$scope: scope});
vm.project = {slug: 'demo', my_permissions: ['modify_task']};
vm.item = Immutable.fromJS({id: 8, model: {ref: 12, subject: 'Task'}});
