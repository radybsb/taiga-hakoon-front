const fs = require('fs');
const path = require('path');
const assert = require('assert');
process.chdir(path.resolve(__dirname, '..'));
const {JSDOM} = require('jsdom');
const coffee = require('coffeescript');
const jade = require('jade');
const dom = new JSDOM('<body></body>', {runScripts: 'outside-only', url: 'http://localhost/'});
const w = dom.window;
w.$ = require('jquery')(w);
w._ = require('lodash');
w.eval(fs.readFileSync('node_modules/angular/angular.js','utf8'));
const app = w.angular.module('taigaComponents', []);
const Immutable = require('immutable');
app.value('$tgLocation', {url: () => {}});
app.value('tgDetailPopup', {open: () => {}});
