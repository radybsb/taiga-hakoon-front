vm.project.archived_code=null; vm.onClickTitle=undefined; scope.$digest(); assert.equal(el.find('a[tg-nav]').length,1);
scope.$destroy(); dom.window.close();
console.log('PASS: normal click opens popup; real task href and modified/middle clicks preserve browser navigation; duplicate clicks, permissions, archives, other cards');
