const fs = require('fs');
const path = require('path');
const assert = require('assert');
const coffee = require('coffeescript');
const jade = require('jade');
const {JSDOM} = require('jsdom');
process.chdir(path.resolve(__dirname, '..'));
const w = new JSDOM('<body></body>', {runScripts: 'outside-only'}).window;
w.eval(fs.readFileSync('node_modules/jquery/dist/jquery.js', 'utf8'));
w.eval(fs.readFileSync('node_modules/angular/angular.js', 'utf8'));
w.angular.module('taigaAdmin', []).filter('translate', () => value => value);
w.eval(coffee.compile(fs.readFileSync('app/coffee/modules/admin/nav.coffee', 'utf8')));
const injector = w.angular.injector(['ng', 'taigaAdmin']);
const root = injector.get('$rootScope');
function mount(section, subsection, archived = false) {
    const scope = root.$new();
    scope.project = {slug: 'demo', archived_code: archived, is_kanban_activated: true};
    scope.roles = [{id: 1, name: 'Developer'}, {id: 2, name: 'Designer'}];
    scope.role = scope.roles[0];
    scope.ctrl = {setRole(role) {scope.role = role;}};
    const html = jade.renderFile('app/partials/includes/modules/admin-menu.jade');
    const el = injector.get('$compile')(`<aside tg-admin-navigation="${section}" tg-admin-subsection="${subsection || ''}">${html}</aside>`)(scope);
    w.document.body.append(el[0]); root.$digest();
    return {scope, el};
}
const {scope, el} = mount('project-profile', 'modules');
assert(el.find('#adminmenu-project-profile').hasClass('active'));
assert(el.find('#adminmenu-modules').hasClass('active'));
const project = el.find('#adminmenu-project-profile > button');
assert.equal(project.attr('aria-expanded'), 'true');
project.trigger('click'); root.$digest(); assert.equal(project.attr('aria-expanded'), 'false');
const attributes = el.find('#adminmenu-project-values > button');
attributes.trigger('click'); root.$digest();
assert.equal(attributes.attr('aria-expanded'), 'true');
assert.equal(project.attr('aria-expanded'), 'false');
assert(el.find('#adminmenu-modules').hasClass('active'), 'Selection survives accordion changes');
assert(el.find('#adminmenu-values-tags a').attr('tg-nav').includes('values-tags'));
const collapse = el.find('.settings-nav-toggle');
assert.equal(collapse.attr('aria-expanded'), 'true');
collapse.trigger('click'); root.$digest();
assert.equal(collapse.attr('aria-expanded'), 'false');
assert(el.find('.admin-menu').hasClass('is-collapsed'));
assert.equal(scope.settingsNavigation.open, 'project-values', 'Collapsing keeps the expanded category');
collapse.trigger('click'); root.$digest();
assert.equal(collapse.attr('aria-expanded'), 'true');
assert(!el.find('.admin-menu').hasClass('is-collapsed'));
assert(el.find('#adminmenu-modules').hasClass('active'));

scope.$destroy(); el.remove();
const permissions = mount('roles');
const roleLinks = permissions.el.find('.admin-submenu-roles a');
assert.equal(roleLinks.length, 2);
roleLinks.eq(1).trigger('click'); root.$digest();
assert.equal(permissions.scope.role.id, 2);
assert(permissions.el.find('[tg-new-role]').length);
permissions.scope.$destroy(); permissions.el.remove();
const archived = mount('project-profile', 'details', true);
assert.equal(archived.el.find('#adminmenu-project-values').length, 0);
assert.equal(archived.el.find('#adminmenu-modules').length, 0);
assert(archived.el.find('#adminmenu-export').length);
archived.scope.$destroy();
w.close();
console.log('PASS: Settings accordion, selected parent/child, routes, role selection/creation, archived project restrictions.');
