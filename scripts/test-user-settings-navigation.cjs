const fs = require('fs');
const path = require('path');
const assert = require('assert');
const coffee = require('coffeescript');
const jade = require('jade');
const {JSDOM} = require('jsdom');
process.chdir(path.resolve(__dirname, '..'));
const w = new JSDOM('<body></body>', {runScripts: 'outside-only'}).window;
w.eval(fs.readFileSync('node_modules/jquery/dist/jquery.js', 'utf8'));
w.eval(fs.readFileSync('node_modules/angular/angular.js', 'utf8'));
w.angular.module('taigaUserSettings', []).filter('translate', () => key => key)
.directive('tgNav', () => ({link(scope, element) {element.on('click', event => event.preventDefault());}}));
w.eval(coffee.compile(fs.readFileSync('app/coffee/modules/user-settings/nav.coffee', 'utf8')));
const injector = w.angular.injector(['ng', 'taigaUserSettings']);
const root = injector.get('$rootScope');
const scope = root.$new();
const template = jade.renderFile('app/partials/includes/modules/user-settings-menu.jade');
const el = injector.get('$compile')(`<aside tg-user-settings-navigation="user-profile">${template}</aside>`)(scope);
w.document.body.append(el[0]); root.$digest();
const toggle = el.find('.user-settings-menu-toggle');
assert.equal(toggle.attr('aria-expanded'), 'false');
assert(el.find('#usersettingsmenu-user-profile').hasClass('active'));
toggle.trigger('click'); root.$digest();
assert.equal(toggle.attr('aria-expanded'), 'true');
assert(el.find('.admin-menu').hasClass('user-settings-menu-open'));
el.find('#usersettingsmenu-change-password a').trigger('click'); root.$digest();
assert.equal(toggle.attr('aria-expanded'), 'false', 'Following a settings link closes the mobile menu');
toggle.trigger('click'); root.$digest();
el.trigger(w.jQuery.Event('keydown', {key: 'Escape'})); root.$digest();
assert.equal(toggle.attr('aria-expanded'), 'false');
assert.equal(w.document.activeElement, toggle[0]);
assert(el.find('#usersettingsmenu-user-profile').hasClass('active'), 'Collapsing preserves selected page');
scope.$destroy(); w.close();
console.log('PASS: User settings menu starts collapsed, toggles, closes on navigation/Escape, restores focus and keeps selection.');
