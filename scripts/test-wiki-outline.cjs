const assert = require('node:assert/strict');
const fs = require('node:fs');
const coffee = require('coffeescript');
const {JSDOM} = require('jsdom');
(async () => {
const w = new JSDOM('<body></body>', {url:'http://localhost/project/demo/wiki/home',runScripts:'outside-only',pretendToBeVisual:true}).window;
w.matchMedia = () => ({matches:true});
let copied;
Object.defineProperty(w.navigator,'clipboard',{value:{writeText:async url=>{copied=url;}}});
w.HTMLElement.prototype.scrollIntoView = function(){this.scrolled=true;};
w.eval(fs.readFileSync('node_modules/angular/angular.js','utf8'));
w.angular.module('taigaWiki',[]).value('$rootElement',w.angular.element(w.document.body)).value('$tgConfirm',{notify:()=>{}});
w.eval(coffee.compile(fs.readFileSync('app/coffee/modules/wiki/outline.coffee','utf8')));
const injector=w.angular.injector(['ng','taigaWiki']);
const scope=injector.get('$rootScope').$new();
scope.item={outline:[{id:'wiki-a',title:'Intro',level:1},{id:'wiki-b',title:'Child',level:2}]};
scope.descriptionState={editing:false};
const el=w.angular.element('<div tg-wiki-outline><div class="js-wysiwyg-html"><h1>Intro</h1><h2>Child</h2></div></div>');
w.document.body.append(el[0]);
injector.get('$compile')(el)(scope);injector.get('$rootScope').$digest();
const settle=()=>new Promise(resolve=>setTimeout(resolve,40));
await settle();
assert.equal(el[0].querySelectorAll('.wiki-copy-chapter-link').length,2);
assert.equal(el[0].querySelector('h1').id,'wiki-a');
injector.get('$location').hash('wiki-b');injector.get('$rootScope').$digest();await settle();
assert.equal(el[0].querySelector('h2').scrolled,true);
assert.equal(w.document.activeElement.id,'wiki-b');
el[0].querySelector('.wiki-copy-chapter-link').click();await settle();
assert.equal(copied,'http://localhost/project/demo/wiki/home#wiki-a');
scope.item.outline[0].title='Renamed';el[0].querySelector('h1').textContent='Renamed';injector.get('$rootScope').$digest();await settle();
assert.equal(el[0].querySelector('h1').id,'wiki-a');
assert.equal(el[0].querySelectorAll('.wiki-copy-chapter-link').length,2);
scope.$destroy();w.close();
console.log('PASS: stable heading anchors, deep-link focus and scrolling, copy links, rerender and cleanup');
})().catch(e=>{console.error(e);process.exitCode=1;});
